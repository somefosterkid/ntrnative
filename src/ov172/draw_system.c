// pokebw2's DrawSystem_DrawLine
static void func_ov172_021b6ca4(DrawSystem *sys, u16 *screen, int x0, int x1, u16 y0, u16 y1, int pen, u16 color) {
    const DrawPen *penData = &data_ov172_021c4e84[pen];
    int dx;
    int dy;
    // The SDK's fx32 and s32 are long, which stores the corner's copies for the loop after the loop's guard
    long stepX, stepY;
    long offsetX, offsetY;
    long i;
    u8 edgeX, edgeY;
    u8 edges;
    u8 row, col;
    int x, y;
    int lastX, lastY;
    int left, top;
    int steps;

    dx = MATH_ABS(x0 - x1);
    dy = MATH_ABS(y0 - y1);
    steps = (dx > dy ? dx : dy) + 1;
    stepX = FX32_CONST(x1 - x0) / steps;
    stepY = FX32_CONST(y1 - y0) / steps;
    offsetX = 0;
    offsetY = 0;
    left = x0 - penData->width / 2;
    top = y0 - penData->height / 2;
    edgeX = stepX >= 0 ? DRAW_PEN_EDGE_RIGHT : DRAW_PEN_EDGE_LEFT;
    edgeY = stepY >= 0 ? DRAW_PEN_EDGE_BOTTOM : DRAW_PEN_EDGE_TOP;
    lastX = left;
    lastY = top;

    for (i = 0; i < steps; i++) {
        x = left + (offsetX >> FX32_SHIFT);
        y = top + (offsetY >> FX32_SHIFT);
        if (i > 0) {
            edges = 0;
            if (x != lastX) {
                edges += edgeX;
            }
            if (y != lastY) {
                edges += edgeY;
            }
        } else {
            edges = DRAW_PEN_ALL;
        }
        for (row = 0; row < penData->height; row++) {
            for (col = 0; col < penData->width; col++) {
                if (penData->shape[row][col] & edges) {
                    func_ov172_021b6e5c(sys, screen, x + col, y + row, color);
                }
            }
        }
        offsetX += stepX;
        offsetY += stepY;
        lastX = x;
        lastY = y;
    }
}

// pokebw2's DrawSystem_PutPixel
static void func_ov172_021b6e5c(DrawSystem *sys, u16 *screen, u16 x, u16 y, u16 color) {
    if (x >= sys->clipLeft && x < sys->clipRight && y >= sys->clipTop && y < sys->clipBottom) {
        *(screen + x + y * DRAW_SCREEN_WIDTH) = color;
    }
}

