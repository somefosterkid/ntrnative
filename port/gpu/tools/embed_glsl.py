#!/usr/bin/env python3
"""port/gpu's shaders as a C table (docs/gpu.md, "Layout"): every shaders/*.glsl, *.vert, *.frag, by name.

    embed_glsl.py --list DIR          the shader files, one absolute path a line, sorted (meson's input list)
    embed_glsl.py OUT.c FILE...       writes OUT.c: const GpuShaderSrc gpu_shader_src[] = {{"name", "text"}, ...}
"""
import os
import sys
from pathlib import Path

EXTS = (".glsl", ".vert", ".frag")


def c_string(text):
    out = []
    for line in text.splitlines():
        esc = line.replace("\\", "\\\\").replace('"', '\\"')
        out.append('    "%s\\n"' % esc)
    return "\n".join(out) if out else '    ""'


def main():
    if len(sys.argv) == 3 and sys.argv[1] == "--list":
        for p in sorted(Path(sys.argv[2]).iterdir()):
            if p.suffix in EXTS:
                print(p.resolve())
        return 0
    out, files = sys.argv[1], sorted(sys.argv[2:], key=os.path.basename)
    with open(out, "w") as f:
        f.write("/* generated by port/gpu/tools/embed_glsl.py from port/gpu/shaders: do not edit */\n")
        f.write('#include "gpu_gl.h"\n\n')
        f.write("const GpuShaderSrc gpu_shader_src[] = {\n")
        for p in files:
            f.write('  {"%s",\n%s},\n' % (os.path.basename(p), c_string(open(p).read())))
        f.write("  {0, 0}};\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
