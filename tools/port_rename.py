#!/usr/bin/env python3
"""The second game's rename header (docs/launcher.md, "One binary, the second game renamed"): White is the same C as
Black compiled with -DWHITE, so its objects define the same 21,000 global names; to link both games into one exe every
global Black's game objects define gets a prefix in White's compile, through a header given with -include before
everything else (`#define GameInit w_GameInit`, ...). A static keeps its name (it cannot clash), and so do the names the
two games share (below). A rename this header misses shows as a duplicate-symbol link error, never as a silent bug.

The list comes from the symbol table of Black's game archives as built (llvm-nm or a GNU-compatible nm, any object
format: ELF, PE/COFF, Mach-O with its leading underscore). Members left out of the list:
- port/src's DS-side stand-ins (sdk_*.c, stub_*.c, linker_syms.c, boot_exit.c: in libgame.a, not compiled for White);
- the SDK files in the game's directories that libntr and libntrsystem call (SHARED below, not compiled for White
  either: both games use Black's copy, whose C is the same file; the ROM build checks it against both ROMs).

    python3 tools/port_rename.py --nm llvm-nm --prefix w_ -o w_rename.h libgame.a libentry.a
    python3 tools/port_rename.py --shared        # the shared game files, one a line (port/meson.build leaves them out)

Mach-O: pass --underscore (the names carry a leading '_' there).
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

# The game files both games share: SDK code in the game's directories that libntr's or libntrsystem's libraries call by
# name (libnnsg2d, libnnsgfd and libdemo the GX/GXS loads, sim7 NVRAM_Init), so one copy must hold their state
SHARED = ["src/main/main_0207e3d0.c", "src/main/main_02083644.c"]

# the type letters of a definition (nm): text, data, bss, read-only, common, weak, small data, indirect
DEFINED = set("TDBRCVWSGIuvwi")
NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def mangled(path):
    """the end of meson's object name for a repo file"""
    return "_" + path.replace("/", "_") + "."


def skip(member):
    m = member.replace("\\", "/").rsplit("/", 1)[-1]
    if "_port_src_" in m:
        return True
    return any(mangled(s) in m for s in SHARED)


def names(nm, archives, underscore):
    out = set()
    for a in archives:
        r = subprocess.run([nm, "-g", "--defined-only", "-A", "-P", a], capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit(f"port_rename.py: {nm} {a}: {r.stderr.strip()[:400]}")
        for line in r.stdout.splitlines():
            # posix format with -A: "lib.a[member.o]: name T value size" (GNU nm: "lib.a[member.o]: name T value size")
            head, sep, rest = line.rpartition("]: ")
            if not sep:
                head, sep, rest = line.partition(": ")
            f = rest.split()
            if len(f) < 2 or f[1] not in DEFINED or skip(head):
                continue
            n = f[0]
            if underscore:
                if not n.startswith("_"):
                    continue
                n = n[1:]
            if NAME.match(n):
                out.add(n)
    return sorted(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("archives", nargs="*")
    ap.add_argument("--nm", default="llvm-nm")
    ap.add_argument("--prefix", default="w_")
    ap.add_argument("--underscore", action="store_true", help="Mach-O: the names have a leading underscore")
    ap.add_argument("-o", "--output")
    ap.add_argument("--shared", action="store_true")
    a = ap.parse_args()
    if a.shared:
        print("\n".join(SHARED))
        return
    if not a.archives or not a.output:
        ap.error("archives and -o are needed")
    ns = names(a.nm, a.archives, a.underscore)
    if len(ns) < 1000:
        sys.exit(f"port_rename.py: only {len(ns)} names in {a.archives}: not the game's archives?")
    text = ("// Generated by tools/port_rename.py from Black's game objects: every global they define, renamed for the\n"
            f"// second game's compile (-include, before port_prefix.h). {len(ns)} names. Don't edit.\n"
            f"#ifndef BWPORT_RENAME_{a.prefix.upper()}H\n#define BWPORT_RENAME_{a.prefix.upper()}H\n"
            "// a renamed name's symbol, for an asm label where a macro hides the rename (port/extern/src/ov096/tr_ai.c)\n"
            "#define BWPORT_RENAME_STR2(x) #x\n#define BWPORT_RENAME_STR(x) BWPORT_RENAME_STR2(x)\n"
            f"#define BWPORT_RENAMED(name) BWPORT_RENAME_STR(__USER_LABEL_PREFIX__) \"{a.prefix}\" name\n"
            + "".join(f"#define {n} {a.prefix}{n}\n" for n in ns) + "#endif\n")
    out = Path(a.output)
    if not out.exists() or out.read_text() != text:   # unchanged: keep its time (meson's custom targets restat)
        out.write_text(text)


if __name__ == "__main__":
    main()
