#!/usr/bin/env python3
"""HGSS: every declaration narrower than its definition (tools/hg_abi_scan.py's rows) declared as defined, for the PC build.

A prototype (a header's or a file's own extern) with a u8/u16/s8/s16 parameter where the definition takes a 32-bit one, or
a 32-bit return where the definition returns u8/u16: SysV clang extends a narrow argument at the caller (and clang 18 a
narrow return in the callee), win64 does neither and clang 21 no longer extends a narrow return, so the 32-bit side reads
garbage upper bits (win3: GF_SndStartFadeOutBGM(u16, u16) defined (int, int): the BGM fade counter, the stairs hang;
dr1: ov12_02261264's u8 return read as u32, the battle order). Each such declaration becomes

    #if defined(SDK_PORT) || defined(NONMATCHING) // as defined in DEF-FILE (tools/pokehg_abi.py)
    <the declaration with the definition's type in each such slot>
    #else
    <the DS declaration>
    #endif

The definition's type is written as it is where the declaring file can name it (a typedef the file uses, an enum of the
function's own file); otherwise as the plain C type of the same size and sign (an enum: int).
Functions in tools/hg_abi_exceptions.txt are left as they are (the definition is the bug there: listed with why).

  python3 tools/pokehg_abi.py                  remake port/subprojects/pokeheartgold-zzabi.patch: a checkout of the pinned
                                               tree with every other patch (build/pokehg_abi), rewritten, `git diff -U2`
  python3 tools/pokehg_abi.py --tree DIR       rewrite DIR in place (prints what it did)
tools/hgss_repin.py runs it at every re-pin; tools/hg_abi_scan.py --gate (run by tools/pokehg_gen.py on a new checkout)
fails on any row this patch does not handle.
"""
import argparse, glob, os, re, subprocess, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hg_abi_scan as S  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAME = 'zzabi'
PATCH = os.path.join(ROOT, 'port/subprojects/pokeheartgold-%s.patch' % NAME)
WORK = os.path.join(ROOT, 'build/pokehg_abi')
GUARD = '#if defined(SDK_PORT) || defined(NONMATCHING) // as defined in %s (tools/pokehg_abi.py)'
C_TYPES = {'int', 'unsigned', 'unsigned int', 'signed int', 'long', 'unsigned long', 'char', 'unsigned char', 'signed char',
           'short', 'unsigned short', 'signed short', 'short int', 'unsigned short int'}
PLAIN = {'s32': 'int', 'u32': 'unsigned int', 'BOOL': 'int', 'fx32': 'int', 'u8': 'unsigned char', 's8': 'signed char',
         'u16': 'unsigned short', 's16': 'short', 'vu8': 'unsigned char', 'vu16': 'unsigned short', 'uint8_t': 'unsigned char',
         'int8_t': 'signed char', 'uint16_t': 'unsigned short', 'int16_t': 'short', 'BOOL8': 'unsigned char'}
HEADER = """pokeheartgold-zzabi.patch (GENERATED by tools/pokehg_abi.py on a checkout with every other patch applied; remake it
after a re-pin or a change to the patches before it: tools/hgss_repin.py does): every declaration tools/hg_abi_scan.py
finds narrower than its definition (%d declarations of %d functions) declared, for the PC build, with the definition's
type in each such slot (the DS form kept under #else). A u8/u16 parameter declared where the definition takes 32 bits:
SysV clang extends the argument at the caller, win64 does not (win3, Handover-ID win3-0001: sound.h's
GF_SndStartFadeOutBGM(u16, u16), defined (int, int): the fade counter got 0x22E6001E instead of 30 on Windows and the
map change's state 7 waited for it forever, the stairs hang). A 32-bit return declared where the definition returns
u8/u16: clang 18 extends it in the callee, win64 and clang 21 do not (dr1: ov12_02261264, the battle order).
Left as they are (tools/hg_abi_exceptions.txt): %s.
"""


def split_raw(params):
    """the top-level comma pieces of a parameter list, unstripped, as (start, end) offsets"""
    out, d, s = [], 0, 0
    for i, ch in enumerate(params):
        d += ch == '('
        d -= ch == ')'
        if ch == ',' and d == 0:
            out.append((s, i)); s = i + 1
    out.append((s, len(params)))
    return out


def type_re(t):
    return re.compile(r'\b' + r'\s+'.join(re.escape(w) for w in t.split()) + r'\b')


def spelled(t, text, own):
    """how the declaring file (text; own: the definition's own file) writes the definition's type t"""
    if t in C_TYPES:
        return t
    if t.startswith('enum '):
        return t if own else 'int'
    if re.search(r'\b%s\b' % re.escape(t), text) or t not in PLAIN and not re.match(r'^[A-Z]\w*ID$', t):
        return t
    return PLAIN.get(t, 'int')


def rewrite(text, name, line, slots, dpath, own):
    """text with the declaration of name that starts at line put under the guard; None if it is not there as expected"""
    for m in S.FN.finditer(text):
        if m.group(2) != name or text.count('\n', 0, m.start()) + 1 != line or m.group(4) != ';':
            continue
        eol = text.find('\n', m.end())
        eol = len(text) if eol < 0 else eol
        if text[m.end():eol].strip() and not text[m.end():eol].strip().startswith(('//', '/*')):
            return None   # more code after the declaration on its line
        ret, params = m.group(1), m.group(3)
        pieces = split_raw(params)
        new = {}
        for slot, a, b in slots:
            if slot == 'return':
                hits = list(type_re(a).finditer(ret))
                if not hits:
                    return None
                h = hits[-1]
                ret = ret[:h.start()] + spelled(b, text, own) + ret[h.end():]
            else:
                s, e = pieces[slot]
                p = params[s:e]
                h = type_re(a).search(p)
                if not h:
                    return None
                new[slot] = p[:h.start()] + spelled(b, text, own) + p[h.end():]
        params = ','.join(new.get(i, params[s:e]) for i, (s, e) in enumerate(pieces))
        decl = text[m.start():m.start(1)] + ret + text[m.end(1):m.start(3)] + params + text[m.end(3):eol]
        old = text[m.start():eol]
        return text[:m.start()] + '\n'.join([GUARD % dpath, decl, '#else', old, '#endif']) + text[eol:]
    return None


def write(tree, exc=None):
    """rewrite tree's rows (not exceptions); (done rows, rows it could not rewrite)"""
    exc = S.exceptions() if exc is None else exc
    rows = [r for r in S.scan(tree) if r[0] not in exc]
    done, bad = [], []
    for r in sorted(rows, key=lambda r: (r[2], -r[3])):   # bottom-up per file: the line numbers above stay
        name, slots, path, line, dpath, _ = r
        f = os.path.join(tree, path)
        text = open(f).read()
        t = rewrite(text, name, line, slots, dpath, path == dpath)
        if t is None:
            bad.append(r)
            continue
        open(f, 'w').write(t)
        done.append(r)
    return done, bad


def checkout():
    """WORK: the pinned tree with every patch but ours applied, all of it in the index (git diff = our rewrite only)"""
    import pokehg_gen as G
    # the patches before ours: the ones that sort after it (zzzdecl) are made against it and do not apply without it
    patches = [p for p in sorted(glob.glob(G.PATCHES)) if os.path.basename(p) < os.path.basename(PATCH)]
    src = os.environ.get('HGSS_SRC')   # tools/hgss_repin.py from its rebase on: the new pin, not vendored yet
    if src:
        rev = subprocess.check_output(['git', '-C', src, 'rev-parse', os.environ.get('HGSS_REV', 'HEAD') + '^{commit}'],
                                      text=True).strip()
        G.G4.checkout(WORK, os.path.abspath(src), rev, patches)
    elif G.vendored():
        G.vendored_checkout(WORK, patches)
    else:
        G.G4.checkout(WORK, G.G4.submodule(G.SUB), G.G4.pinned(G.SUB), patches)
    subprocess.check_call(['git', '-C', WORK, 'add', '-A', '.'])


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--tree', help='rewrite this tree in place (no patch)')
    a = ap.parse_args(argv)
    exc = S.exceptions()
    tree = a.tree or WORK
    if not a.tree:
        checkout()
    done, bad = write(tree, exc)
    for r in bad:
        print('NOT REWRITTEN %s\t%s\t%s:%d' % (r[0], S.what(r[1]), r[2], r[3]))
    print('%d declarations of %d functions declared as defined; %d exceptions; %d not rewritten' % (
        len(done), len({r[0] for r in done}), len(exc), len(bad)))
    if not a.tree:
        body = subprocess.check_output(['git', '-C', WORK, 'diff', '-U2'], text=True)
        open(PATCH, 'w').write(HEADER % (len(done), len({r[0] for r in done}),
                                         ', '.join(sorted(exc)) or 'none') + body)
        print('wrote %s' % os.path.relpath(PATCH, ROOT))
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
